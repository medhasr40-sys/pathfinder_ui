const inHours = (h) => new Date(Date.now() + h * 3600000).toISOString()

// Tonight at 11:59 PM, or 6 hours from now if it's already very late
const tonight = () => {
  const d = new Date()
  d.setHours(23, 59, 0, 0)
  return d - Date.now() > 2 * 3600000 ? d.toISOString() : inHours(6)
}

// A date `days` from today at a given clock time, e.g. at(2, 14) = day after tomorrow, 2 PM
const at = (days, hour, minute = 0) => {
  const d = new Date()
  d.setDate(d.getDate() + days)
  d.setHours(hour, minute, 0, 0)
  return d.toISOString()
}

